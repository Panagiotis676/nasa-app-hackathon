"""Build the "Night lights 2012-2023" preset for the web jukebox (index.html).

Chrysanthos: this is so a blind user can just pick the map and press Play,
without having to load images or read a colorbar first.

What it does:
  1. downloads NASA's yearly night lights maps (Black Marble, SVS #5276, used in
     the EIC version #5313). One 8K TIFF per year, ~9 MB each, cached in a temp folder
  2. blacks out the year label NASA prints in the South Atlantic (otherwise the
     text would be "heard" as lights)
  3. resizes to a normal 2:1 world map (the originals are the whole globe
     stretched to 16:9)
  4. writes data/nightlights.js with the frames as base64 JPEGs

Why a .js file and not plain .jpg files: the page reads pixels from a canvas, and
Chrome blocks that for local files when you just double-click index.html. Images
that come in as data: URLs work everywhere, including GitHub Pages.

Run:
    pip install pillow numpy
    python tools/build_nightlights.py
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import tempfile
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None  # the source frames are 7680x4320

ROOT = Path(__file__).resolve().parent.parent
SVS = "https://svs.gsfc.nasa.gov/vis/a000000/a005200/a005276/frames/7680x4320_16x9_3p/nightlights_flat_2012-2023_only_lights"
YEARS = list(range(2012, 2024))

# where the year label sits, as a fraction of the frame (x0, x1, y0, y1).
# Found by looking for the grey text pixels, plus a bit of margin. It's open ocean
# (roughly 27W-4W, 18S-27S), so blacking it out doesn't hide any real lights.
LABEL_BOX = (0.425, 0.490, 0.600, 0.652)

PRESET = {
    "id": "nightlights",
    "title": "NASA: Earth's night lights, 2012 to 2023",
    "intro": (
        "NASA Black Marble satellite data: the lights on Earth at night, one map for each year "
        "from 2012 to 2023. Each year the sound sweeps from the west edge of the map in your left "
        "ear to the east edge in your right ear. Louder means brighter lights. Listen for the "
        "lights growing over the years, with a small dip in 2020."
    ),
    "loudness": (
        "Louder means brighter night lights, like big cities. Silence means darkness: "
        "oceans, deserts, forests and ice."
    ),
    "source": "NASA Scientific Visualization Studio, https://svs.gsfc.nasa.gov/5276/",
    "cmap": "gray",
    "vmin": 0,
    # Chrysanthos: the maps are mostly black, a 12-row band of the map almost never
    # averages above ~0.1 brightness. With 0..1 you hear basically nothing, so the
    # loudest sound is set at 0.08 (about the brightest 1% of the map).
    "vmax": 0.08,
    "units": "brightness",
    "lat": [-90, 90],
    "lon": [-180, 180],
}


def download(year: int, cache: Path) -> Path:
    path = cache / f"nightlights_{year}.tif"
    if not path.exists():
        url = f"{SVS}/nightlights_flat_series_stills_8k_only_lights.{year}.tif"
        print(f"  downloading {year} ...")
        tmp = path.with_suffix(".part")
        urllib.request.urlretrieve(url, tmp)
        tmp.rename(path)
    return path


def prepare(path: Path, width: int) -> Image.Image:
    rgb = np.asarray(Image.open(path).convert("RGB")).copy()
    h, w = rgb.shape[:2]
    x0, x1, y0, y1 = LABEL_BOX
    rgb[int(h * y0) : int(h * y1), int(w * x0) : int(w * x1)] = 0
    return Image.fromarray(rgb).resize((width, width // 2), Image.BOX)


def to_data_url(img: Image.Image, quality: int) -> str:
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=quality, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "earth_jukebox_cache")
    p.add_argument("--width", type=int, default=1024, help="output map width in px (height = width / 2)")
    p.add_argument("--quality", type=int, default=82, help="JPEG quality")
    p.add_argument("--out", type=Path, default=ROOT / "data" / "nightlights.js")
    a = p.parse_args()

    a.cache.mkdir(parents=True, exist_ok=True)
    a.out.parent.mkdir(parents=True, exist_ok=True)

    frames = []
    for year in YEARS:
        img = prepare(download(year, a.cache), a.width)
        mean = np.asarray(img.convert("L"), dtype=np.float32).mean() / 255
        print(f"  {year}: mean brightness {mean:.4f}")
        frames.append({"name": str(year), "src": to_data_url(img, a.quality)})

    preset = dict(PRESET, frames=frames)
    js = (
        "// Generated by tools/build_nightlights.py, don't edit by hand.\n"
        "// Source: NASA SVS #5276 (Black Marble yearly night lights). Year labels blacked out.\n"
        "window.EJ_PRESETS = window.EJ_PRESETS || {};\n"
        f"window.EJ_PRESETS.nightlights = {json.dumps(preset, ensure_ascii=False)};\n"
    )
    a.out.write_text(js, encoding="utf-8")
    print(f"wrote {a.out} ({a.out.stat().st_size / 1024:.0f} KB, {len(frames)} frames)")


if __name__ == "__main__":
    main()
